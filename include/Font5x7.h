// Ищет битовую маску нужного символа в таблице kGlyphs (все буквы приводятся к верхнему регистру)
inline const char* findGlyph(char c) {
    char u = static_cast<char>(std::toupper(static_cast<unsigned char>(c)));
    if (c == 'x') u = 'x';
    for (const Glyph& g : kGlyphs) {
        if (g.c == u) return g.rows;
    }
    return nullptr;
}

// Проверяет, закрашен ли конкретный пиксель (col, row) внутри глифа 5x7
inline bool glyphPixel(const char* rows, int col, int row) {
    return rows[row * 5 + col] == '#';
}

